import { alignModel, cameraCenters } from "../view-math.js";

/**
 * Light positions by LED index, centered, leveled and scaled so the farthest light is at distance 1.
 * (The scale of a reconstruction from video is arbitrary.) Lights that were not found are null.
 */
export function ledPositions(raw) {
  const aligned = alignModel(raw.points.map(p => [p.x, p.y, p.z]), cameraCenters(raw.cameras));
  const positions = Array.from({ length: raw.count }, () => null);
  raw.points.forEach((p, k) => { if (p.index < raw.count) positions[p.index] = aligned.lights[k].map(v => v / aligned.radius); });
  return positions;
}

/** A C++ header with one {x, y, z} per LED index, ready for the Arduino code. */
export function toHpp(raw) {
  const positions = ledPositions(raw);
  const missing = positions.flatMap((p, i) => p ? [] : [i]);
  const number = v => `${v.toFixed(5)}f`;
  const rows = positions.map((p, i) => p ? `  {${p.map(number).join(", ")}},  // ${i}` : `  {NAN, NAN, NAN},  // ${i} (not found)`);
  return [
    "#pragma once",
    "#include <math.h>",
    "",
    "// Generated by Mapper3D.",
    ...(raw.kind === "projection" ? ["// Approximate single-view projection; depth and perspective are not recovered."] : []),
    "// Positions are centered on the lights, with z up, scaled so the farthest light is at distance 1.",
    `// Lights that were not found${missing.length ? ` (${missing.join(", ")})` : ""} are NAN.`,
    "",
    `constexpr int LED_COUNT = ${raw.count};`,
    "",
    "struct LedPosition { float x, y, z; };",
    "",
    "constexpr LedPosition LED_POSITIONS[LED_COUNT] = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

export function download(name, text, type) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const link = Object.assign(document.createElement("a"), { href: url, download: name });
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
